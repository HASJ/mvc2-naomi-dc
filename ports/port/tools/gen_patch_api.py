"""Generate MVC2_HOST_API bindings and dc_game.dll thunks from undefined symbols in dc.o.

usage: gen_patch_api.py NM DC_O OUTDIR GAME_DIR [--underscore]
"""
import hashlib
import subprocess
import sys
from pathlib import Path

LIBC = {
    "memset", "memcpy", "memmove", "memcmp", "strcpy", "strncpy", "strlen", "strcmp", "strncmp", "strcat",
    "sprintf", "vsprintf", "snprintf", "vsnprintf", "printf", "sqrtf", "sinf", "cosf", "tanf", "fabsf",
    "floorf", "ceilf", "fmodf", "powf", "atan2f", "atanf", "acosf", "asinf", "sqrt", "sin", "cos", "rand",
    "srand", "abs", "atoi", "strchr", "memchr",
}


def compute_patch_id(game_dir: Path) -> str:
    h = hashlib.sha256()
    roots = [game_dir / "src", game_dir / "include"]
    files = []
    for r in roots:
        if r.exists():
            for p in r.rglob("*"):
                if p.is_file() and p.suffix.lower() in (".c", ".h"):
                    files.append(p)
    for p in sorted(files, key=lambda x: x.relative_to(game_dir).as_posix()):
        rel = p.relative_to(game_dir).as_posix()
        h.update(rel.encode("utf-8"))
        h.update(b"\0")
        h.update(p.read_bytes().replace(b"\r\n", b"\n"))
        h.update(b"\0")
    return f"umvsc2-20000529-{h.hexdigest()[:8]}"


def fnv1a_names(names) -> int:
    h = 14695981039346656037
    for n in names:
        for b in n.encode("utf-8"):
            h ^= b
            h = (h * 1099511628211) & 0xFFFFFFFFFFFFFFFF
        h ^= 0
        h = (h * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return h


def read_undefined(nm: str, dc_o: Path, underscore: bool):
    out = subprocess.run([nm, "-u", str(dc_o)], capture_output=True, text=True, check=True).stdout.splitlines()
    syms = set()
    for line in out:
        parts = line.split()
        if len(parts) < 2 or parts[-2] != "U":
            continue
        raw = parts[-1]
        name = raw[1:] if underscore and raw.startswith("_") else raw
        if name.startswith("dc.") or name.startswith("_") or name in LIBC:
            continue
        syms.add(name)
    return sorted(syms)


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    flags = set(a for a in sys.argv[1:] if a.startswith("--"))
    if len(args) != 4:
        sys.exit("usage: gen_patch_api.py NM DC_O OUTDIR GAME_DIR [--underscore]")
    nm = args[0]
    dc_o = Path(args[1])
    outdir = Path(args[2])
    game_dir = Path(args[3])
    underscore = "--underscore" in flags

    outdir.mkdir(parents=True, exist_ok=True)
    syms = read_undefined(nm, dc_o, underscore)
    sym_hash = fnv1a_names(syms)
    patch_id = compute_patch_id(game_dir)
    prefix = "_" if underscore else ""

    header = [
        "/* generated by gen_patch_api.py -- do not edit */",
        "#ifndef PATCH_API_GEN_H",
        "#define PATCH_API_GEN_H",
        "#include <stdint.h>",
        "#define MVC2_HOST_API_VERSION 1u",
        f"#define MVC2_HOST_API_FN_COUNT {len(syms)}u",
        f"#define MVC2_HOST_API_SYM_HASH 0x{sym_hash:016X}ULL",
        f'#define MVC2_DEFAULT_PATCH_ID "{patch_id}"',
        "",
        "typedef struct MVC2_HOST_API {",
        "    uint32_t api_version;",
        "    uint32_t fn_count;",
        "    uint64_t api_sym_hash;",
        "    const void* (*resolve)(const char* name);",
        "    const void* fn[MVC2_HOST_API_FN_COUNT];",
        "} MVC2_HOST_API;",
        "",
        "const MVC2_HOST_API* host_get_patch_api(void);",
        "#endif",
        "",
    ]
    (outdir / "patch_api_gen.h").write_text("\n".join(header), encoding="utf-8", newline="\n")

    fill = [
        "/* generated by gen_patch_api.py -- do not edit */",
        "#include <stddef.h>",
        "#include <stdlib.h>",
        "#include <string.h>",
        '#include "patch_api_gen.h"',
        "",
    ]
    for s in syms:
        fill.append(f"extern void {s}(void);")
    fill += [
        "",
        "typedef struct API_ENTRY {",
        "    const char* name;",
        "    const void* ptr;",
        "} API_ENTRY;",
        "",
        "static const API_ENTRY api_lookup[MVC2_HOST_API_FN_COUNT] = {",
    ]
    for s in syms:
        fill.append(f'    {{ "{s}", (const void*){s} }},')
    fill += [
        "};",
        "",
        "static int api_cmp(const void* key, const void* elem) {",
        "    const char* name = (const char*)key;",
        "    const API_ENTRY* e = (const API_ENTRY*)elem;",
        "    return strcmp(name, e->name);",
        "}",
        "",
        "static const void* api_resolve(const char* name) {",
        "    const API_ENTRY* e;",
        "    if (name == NULL) return NULL;",
        "    e = (const API_ENTRY*)bsearch(name, api_lookup, MVC2_HOST_API_FN_COUNT, sizeof api_lookup[0], api_cmp);",
        "    return e != NULL ? e->ptr : NULL;",
        "}",
        "",
        "static const MVC2_HOST_API g_mvc2_host_api = {",
        "    MVC2_HOST_API_VERSION,",
        "    MVC2_HOST_API_FN_COUNT,",
        "    MVC2_HOST_API_SYM_HASH,",
        "    api_resolve,",
        "    {",
    ]
    for s in syms:
        fill.append(f"        (const void*){s},")
    fill += [
        "    }",
        "};",
        "",
        "const MVC2_HOST_API* host_get_patch_api(void) {",
        "    return &g_mvc2_host_api;",
        "}",
        "",
    ]
    (outdir / "host_api_fill.c").write_text("\n".join(fill), encoding="utf-8", newline="\n")

    thunks = [
        "/* generated by gen_patch_api.py -- do not edit */",
        "#include <stddef.h>",
        '#include "naomi_host.h"',
        '#include "patch_api_gen.h"',
        "",
        "extern const HOST_PROGRAM dc_program;",
        "const void* mvc2_api_fn[MVC2_HOST_API_FN_COUNT];",
        "",
        "static const char* const mvc2_api_names[MVC2_HOST_API_FN_COUNT] = {",
    ]
    for s in syms:
        thunks.append(f'    "{s}",')
    thunks += [
        "};",
        "",
        "__declspec(dllexport) const HOST_PROGRAM* mvc2_patch_bind(const MVC2_HOST_API* api) {",
        "    uint32_t i;",
        "    if (api == NULL || api->api_version != MVC2_HOST_API_VERSION) {",
        "        return NULL;",
        "    }",
        "    if (api->fn_count == MVC2_HOST_API_FN_COUNT && api->api_sym_hash == MVC2_HOST_API_SYM_HASH) {",
        "        for (i = 0; i < MVC2_HOST_API_FN_COUNT; i++) {",
        "            if (api->fn[i] == NULL) return NULL;",
        "            mvc2_api_fn[i] = api->fn[i];",
        "        }",
        "        return &dc_program;",
        "    }",
        "    if (api->resolve == NULL) {",
        "        return NULL;",
        "    }",
        "    for (i = 0; i < MVC2_HOST_API_FN_COUNT; i++) {",
        "        const void* p = api->resolve(mvc2_api_names[i]);",
        "        if (p == NULL) return NULL;",
        "        mvc2_api_fn[i] = p;",
        "    }",
        "    return &dc_program;",
        "}",
        "",
        "__declspec(dllexport) const char* mvc2_patch_id(void) {",
        "    return MVC2_DEFAULT_PATCH_ID;",
        "}",
        "",
        '__asm__(".text\\n"',
    ]
    for idx, s in enumerate(syms):
        thunks.append(f'    ".globl {prefix}{s}\\n"')
        thunks.append(f'    "{prefix}{s}:\\n"')
        thunks.append(f'    "    jmp *({prefix}mvc2_api_fn + {idx * 4})\\n"')
    thunks.append(");")
    thunks.append("")
    (outdir / "dll_thunks.c").write_text("\n".join(thunks), encoding="utf-8", newline="\n")
    (outdir / "patch_id.txt").write_text(patch_id, encoding="utf-8", newline="\n")
    print(f"gen_patch_api: {len(syms)} host functions, patch_id={patch_id}")


if __name__ == "__main__":
    main()
